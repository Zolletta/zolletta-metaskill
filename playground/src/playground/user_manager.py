    def reconcile_accounts(self, accounts, verbose):
        result = []
        for account in accounts:
            if account is None:
                continue
            status = account.get("status")
            if status == "active":
                if account.get("balance", 0) > 1000:
                    tier = "gold"
                elif account.get("balance", 0) > 500:
                    tier = "silver"
                elif account.get("balance", 0) > 100:
                    tier = "bronze"
                else:
                    tier = "standard"
                result.append({"id": account["id"], "tier": tier})
            elif status == "pending":
                if account.get("attempts", 0) > 3:
                    result.append({"id": account["id"], "tier": "review"})
                elif account.get("attempts", 0) > 1:
                    result.append({"id": account["id"], "tier": "retry"})
                else:
                    result.append({"id": account["id"], "tier": "new"})
            elif status == "suspended":
                if account.get("violations", 0) > 5:
                    result.append({"id": account["id"], "tier": "banned"})
                elif account.get("violations", 0) > 2:
                    result.append({"id": account["id"], "tier": "warning"})
                else:
                    result.append({"id": account["id"], "tier": "probation"})
            elif status == "closed":
                result.append({"id": account["id"], "tier": "archived"})
            elif status == "trial":
                if account.get("days_left", 0) > 14:
                    result.append({"id": account["id"], "tier": "trial-long"})
                else:
                    result.append({"id": account["id"], "tier": "trial-short"})
            else:
                result.append({"id": account.get("id"), "tier": "unknown"})
        return result

