#!/usr/bin/env bash
# Regenerate the installable bundle's copied files.
#
# The repository keeps a single source of truth for documentation at its root
# (docs/, README.md, LICENSE, ...). The installable bundle under
# skills/zolletta-metaskill/ ships only what the skill references: SKILL.md and
# every SUBCOMMAND point at docs via bundle-relative paths (../../docs/...), so
# each referenced source file is physically copied into the bundle at the
# matching position. Copies are committed — `npx skills` and `gh skill`
# install straight from git and never run this script.
#
# The copy list lives in bundle-files.txt. Two modes:
#
#   ./sync-bundle.sh              # copy everything in bundle-files.txt,
#                                  # remove stale generated files
#   ./sync-bundle.sh --regenerate # recompute the list from SKILL.md/SUBCOMMAND
#                                  # references, rewrite bundle-files.txt,
#                                  # then sync
#
# Copied .md files get `skills/zolletta-metaskill/` stripped from link targets
# and prose: in the installed bundle those paths are src/, skills/, docs/
# relative to the skill root. Heading anchors that slugged the same prefix
# (`skillszolletta-metaskill<slug>`) get the matching strip.
#
# Safety: this script NEVER uses rm -rf. Deletion uses rm/find -delete on
# paths listed in the repo-root .sync-manifest or under the generated docs/
# directory only. The manifest lives outside the bundle so it is not shipped.
# Portability: bash 3.2-compatible (stock macOS), no associative arrays.

set -euo pipefail

ROOT="$(cd "$(dirname "$0")" && pwd)"
cd "$ROOT"
BUNDLE="skills/zolletta-metaskill"
LIST="bundle-files.txt"
MANIFEST=".sync-manifest"
SEEN="$(mktemp)"
trap 'rm -f "$SEEN"' EXIT

# ---------------------------------------------------------------------------
# List handling
# ---------------------------------------------------------------------------

read_list() {
    # Print normalized (deduplicated, sorted) entries from bundle-files.txt.
    sed 's/#.*//; s/[[:space:]]//g' "$LIST" | grep -v '^$' | sort -u
}

# ---------------------------------------------------------------------------
# --regenerate: recompute bundle-files.txt from the reference closure
# ---------------------------------------------------------------------------

norm() {
    # Lexically normalize a relative path (resolve . and .. components).
    local -a stack=() parts
    IFS='/' read -ra parts <<< "$1"
    for p in "${parts[@]}"; do
        case "$p" in
            ""|.) ;;
            ..) ((${#stack[@]})) && unset 'stack[${#stack[@]}-1]' ;;
            *) stack+=("$p") ;;
        esac
    done
    local IFS='/'
    echo "${stack[*]}"
}

emit_refs() {
    # Print repo-relative paths referenced by file $1:
    #  - docs/...md tokens (markdown links and inline-code references alike)
    #  - markdown link/image targets ](...) normalized against the file's dir
    local f="$1" dir
    dir="$(dirname "$f")"
    grep -ohE 'docs/[A-Za-z0-9_./-]+\.md' "$f" || true
    grep -ohE '\]\([^)[:space:]]+' "$f" \
        | sed 's/^](//; s/#.*//' \
        | grep -vE '^(https?:|mailto:|/|[a-z]+://)' \
        | while IFS= read -r t; do norm "$dir/$t"; done
}

map_target() {
    # Map a normalized repo-relative target to a list entry (or nothing).
    case "$1" in
        "$BUNDLE"/docs/*) echo "${1#"$BUNDLE"/}" ;;   # generated docs slot
        "$BUNDLE"/*) ;;                                # real bundle content
        *) echo "$1" ;;                               # outside → same path
    esac
}

regenerate() {
    local -a queue=( "$BUNDLE/SKILL.md" )
    : > "$SEEN"
    local f
    while IFS= read -r f; do queue+=("$f"); done \
        < <(find "$BUNDLE/skills" -name '*.md' | sort)

    # BFS: each referenced docs/*.md is scanned in turn for further refs.
    while ((${#queue[@]})); do
        f="${queue[0]}"
        queue=("${queue[@]:1}")
        [[ -f $f ]] || continue
        while IFS= read -r target; do
            local entry
            entry="$(map_target "$target")"
            [[ -n $entry && -f $entry ]] || continue
            if ! grep -qxF "$entry" "$SEEN"; then
                echo "$entry" >> "$SEEN"
                # Follow .md sources too — a copied CONTRIBUTING.md that links
                # .github/workflows/tests.yml must ship the workflow file or
                # its link dangles in the installed bundle.
                [[ $entry == *.md ]] && queue+=("$entry")
            fi
        done < <(emit_refs "$f")
    done

    {
        cat <<'HDR'
# Files copied into skills/zolletta-metaskill/ at the same relative path by
# sync-bundle.sh — the bundle's single source of truth for what it ships.
# Everything a SKILL.md/SUBCOMMAND reference needs must be listed here.
#
# Regenerated by `./sync-bundle.sh --regenerate` (the list is the link/token
# closure of the skill entry points). link_checker reports dangling
# ../../docs/... references in the entry points if a file is missing.
HDR
        sort "$SEEN"
    } > "$LIST"
    echo "sync-bundle: regenerated $LIST ($(wc -l < "$SEEN" | tr -d ' ') entries)"
}

# ---------------------------------------------------------------------------
# sync: copy the listed files into the bundle
# ---------------------------------------------------------------------------

sync() {
    read_list > "$SEEN"
    local f old dest

    # Remove files we generated before that are no longer listed.
    if [[ -f $MANIFEST ]]; then
        while IFS= read -r old; do
            if [[ -n $old ]] && ! grep -qxF "$old" "$SEEN"; then
                rm -f "$BUNDLE/$old"
                echo "removed stale: $old"
            fi
        done < "$MANIFEST"
    fi
    # The generated docs tree is fully owned by this script.
    find "$BUNDLE/docs" -mindepth 1 -delete 2>/dev/null || true

    local count=0
    while IFS= read -r f; do
        if [[ ! -f $f ]]; then
            echo "sync-bundle: missing source: $f" >&2
            exit 1
        fi
        dest="$BUNDLE/$f"
        mkdir -p "$(dirname "$dest")"
        if [[ $f == *.md ]]; then
            # Strip the bundle prefix so repo-relative paths become
            # bundle-relative (skills/zolletta-metaskill/skills/x -> skills/x).
            # The second expression does the same inside #heading-anchors:
            # a heading like `### skills/zolletta-metaskill/src/x.py` slugs to
            # `skillszolletta-metaskillsrcxpy`, so anchors to it need the same
            # strip. Firing only before [a-z0-9_] keeps the slugs of real
            # sibling dirs (skills/zolletta-metaskill-foo -> ...-foo) intact.
            sed -e 's|skills/zolletta-metaskill/||g' \
                -e 's/skillszolletta-metaskill\([a-z0-9_]\)/\1/g' \
                "$f" > "$dest"
            # The prefix strip shortens table cells that carry a
            # skills/zolletta-metaskill/ path without re-padding the column,
            # so copied tables can lose their markdown-table-prettify layout
            # (documentation.8). Re-align only files that contain a table —
            # npx stays idle on table-less docs.
            if command -v npx >/dev/null 2>&1 && grep -qE '^[[:space:]]*\|.*\|' "$dest"; then
                npx --yes markdown-table-prettify@4.1.0 < "$dest" > "$dest.pretty"
                # The prettifier drops the trailing newline — restore it
                # (general.1 requires it on every file).
                if [ -s "$dest.pretty" ] && [ "$(tail -c1 "$dest.pretty" | wc -l)" -eq 0 ]; then
                    printf '\n' >> "$dest.pretty"
                fi
                mv "$dest.pretty" "$dest"
            fi
        else
            cp "$f" "$dest"
        fi
        count=$((count + 1))
    done < "$SEEN"

    cp "$SEEN" "$MANIFEST"
    echo "sync-bundle: $count files copied into $BUNDLE"
}

if [[ ${1:-} == "--regenerate" ]]; then
    regenerate
    sync
elif [[ -z ${1:-} ]]; then
    sync
else
    echo "usage: $0 [--regenerate]" >&2
    exit 1
fi
